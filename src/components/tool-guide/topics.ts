const normalize=(s:string)=>s.normalize('NFKC').toLocaleLowerCase().replace(/\s+/g,'');
export function findGuideTopics(query:string,group:string='all'){
 const tokens=query.trim().split(/\s+/).map(normalize).filter(Boolean);
 return GUIDE_TOPICS.filter(topic=>(group==='all'||topic.group===group)&&tokens.every(token=>normalize([topic.name,topic.summary,...topic.steps,topic.tip??'',...(topic.aliases??[])].join(' ')).includes(token)));
}
